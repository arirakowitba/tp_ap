"""Full 70k Refit of Enriched LightGBM with Second-Order Tabular & Subword Text Signals.

Generates test probabilities for 30,000 items to blend with CatBoost Native/NB.
Strictly train-only reference: no Kaggle upload.
"""

import os, sys, json, time, hashlib, zipfile, gc
from pathlib import Path
import numpy as np, pandas as pd
import lightgbm as lgb
from scipy import sparse

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.revision_submissions.deep_catboost_nbsvm_ablation_20261029 import extract_deep_features

OUT_DIR = ROOT / "results" / "full_lightgbm_enriched_70k_20261105"
OUT_DIR.mkdir(parents=True, exist_ok=True)

SEED = 20261144

def sha256_lf(path):
    data = path.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()

def main():
    print("=== FULL 70K REFIT OF ENRICHED LIGHTGBM ===", flush=True)
    t0 = time.time()

    # 1. Load Data from Zip
    zip_path = ROOT / "data_local" / "ap-2026-q-2.zip"
    print(f"Loading data from {zip_path.name}...", flush=True)
    with zipfile.ZipFile(zip_path) as z:
        train_rows = [json.loads(line) for line in z.open("train_data.jsonlines")]
        test_rows = [json.loads(line) for line in z.open("test_data.jsonlines")]

    assert len(train_rows) == 70000 and len(test_rows) == 30000
    rows = train_rows + test_rows
    y_train = np.array([int(r["condition"] == "used") for r in train_rows], dtype=np.int8)

    # 2. Extract Deep Tabular Features
    print("Extracting deep tabular features on 100k...", flush=True)
    af, cat, _, _, _ = extract_deep_features(rows)
    df = af[[c for c in af.columns if not c.startswith(("freq_", "seller_", "sell_mean_", "rel_price_cat"))]].copy()

    # Fit-only frequencies
    for col in ["seller_id", "category_id", "city"]:
        counts = cat.iloc[:70000][col].value_counts()
        df["fit_freq_" + col] = cat[col].map(counts).fillna(0).astype(float)

    # Fit-only relative price
    med = df.iloc[:70000].groupby(cat.iloc[:70000].category_id).log_price.median()
    df["fit_rel_price"] = df.log_price - cat.category_id.map(med).fillna(float(df.iloc[:70000].log_price.median()))

    # Second-order features: attr_count, has_warranty, title_len
    attr_counts = np.array([len(r.get("attributes", []) or []) for r in rows], dtype=np.float32)
    has_warranty = np.array([int(bool(str(r.get("warranty", "")).strip().lower() not in ["", "sin garantia", "no", "none", "0"])) for r in rows], dtype=np.float32)
    title_lens = np.array([len(str(r.get("title", ""))) for r in rows], dtype=np.float32)

    df["attr_count"] = attr_counts
    df["has_warranty"] = has_warranty
    df["title_len"] = title_lens

    # Categorical columns
    cat_cols = ["category_id", "listing_type_id", "buying_mode", "currency_id", "status", "seller_id", "state", "ship_mode"]
    for key in cat_cols[:6]:
        df[key] = [str(r.get(key) or "MISSING") for r in rows]
    df["state"] = [str(((r.get("seller_address") or {}).get("state") or {}).get("id") or "MISSING") for r in rows]
    df["ship_mode"] = [str((r.get("shipping") or {}).get("mode") or "MISSING") for r in rows]

    # Convert categoricals to category dtype for LightGBM
    for c in cat_cols:
        df[c] = df[c].astype("category")

    # 3. Add Subword Rich Text Signal
    # Load subword test probabilities generated by Frente C
    p_text_oof = np.load(ROOT / "results" / "frente_c_subword_and_diagnostics_20261104" / "oof_probs_subword_rich_text.npy")
    p_text_test = np.load(ROOT / "results" / "frente_c_subword_and_diagnostics_20261104" / "test_probs_subword_rich_text.npy")
    p_text_all = np.concatenate([p_text_oof, p_text_test])
    df["p_subword_rich_text"] = p_text_all

    del rows, train_rows, test_rows, af; gc.collect()
    print(f"Features ready in {time.time()-t0:.1f}s, feature shape: {df.shape}")

    # 4. Train LightGBM on full 70k
    print("Training LightGBM on full 70,000 observations (6 threads)...", flush=True)
    d_train = lgb.Dataset(df.iloc[:70000], label=y_train)

    params = {
        "objective": "binary",
        "metric": "binary_logloss",
        "boosting_type": "gbdt",
        "learning_rate": 0.05,
        "num_leaves": 45,
        "max_depth": 7,
        "feature_fraction": 0.8,
        "bagging_fraction": 0.8,
        "subsample_freq": 1,
        "seed": SEED,
        "num_threads": 6,
        "verbose": -1
    }

    t_fit = time.time()
    m_lgb = lgb.train(params, d_train, num_boost_round=850)
    print(f"LightGBM fitted in {time.time()-t_fit:.1f}s", flush=True)

    # 5. Predict Test Probabilities (30,000)
    print("Predicting test set (30,000 observations)...", flush=True)
    p_lgb_test = m_lgb.predict(df.iloc[70000:])
    np.save(OUT_DIR / "lgb_enriched_test_probs.npy", p_lgb_test)
    m_lgb.save_model(str(OUT_DIR / "lgb_enriched_model.txt"))

    df_preds = pd.DataFrame({
        "ID": range(1, 30001),
        "p_lgb_enriched": p_lgb_test
    })
    path_csv = OUT_DIR / "lgb_enriched_test_probabilities.csv"
    df_preds.to_csv(path_csv, index=False)
    sha_csv = sha256_lf(path_csv)

    manifest = {
        "model": "LightGBM Enriched Full 70k Refit",
        "num_boost_round": 850,
        "features": list(df.columns),
        "n_features": df.shape[1],
        "test_probs_sha256": sha_csv,
        "duration_seconds": float(time.time() - t0)
    }
    with open(OUT_DIR / "manifest.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print(f"\nLightGBM full refit finished in {time.time()-t0:.1f}s! Artifacts in {OUT_DIR.name}")

if __name__ == "__main__":
    main()
